# BRAND-6: regenerate web/brand-marks.js from the owner's brand handoff PNGs (handoff/brand/logo).
# Needs Pillow (a dev tool, not a repo dependency).
#   python3 tools/brand/brand-marks.py <handoff/brand/logo> web/brand-marks.js
# Each mark is carried two ways, both from the handoff's WHITE artwork's alpha channel:
#   png   the handoff file itself, base64 -- the SVG preview masks a fill colour with it
#   bits  a 1-bit stencil (alpha >= 128 = ink), rows packed MSB first, base64 -- the PDF draws it
#         as an /ImageMask in the element's spot colour, so a print plate stays one ink
import sys, json, base64
from PIL import Image
src, out = sys.argv[1], sys.argv[2]
marks = {}
for name, f in [('icon', 'rac-icon-shell-fluke-white.png'), ('wordmark', 'rac-wordmark-white.png')]:
    path = f'{src}/{f}'
    im = Image.open(path).convert('RGBA'); w, h = im.size; a = im.getchannel('A').load()
    rows = bytearray()
    for y in range(h):
        byte = 0; n = 0
        for x in range(w):
            byte = (byte << 1) | (1 if a[x, y] >= 128 else 0); n += 1
            if n == 8: rows.append(byte); byte = 0; n = 0
        if n: rows.append(byte << (8 - n))
    marks[name] = {'file': f, 'w': w, 'h': h, 'png': base64.b64encode(open(path, 'rb').read()).decode(), 'bits': base64.b64encode(bytes(rows)).decode()}
js = ("/* BRAND-6: the RAC Shell Fluke icon and wordmark from the owner's brand handoff\n"
      " * (handoff/brand/logo, rac-icon-shell-fluke-white.png and rac-wordmark-white.png). GENERATED by\n"
      " * tools/brand/brand-marks.py; do not hand-edit. png = the handoff file; bits = its alpha as a\n"
      " * 1-bit stencil (rows MSB first, 1 = ink). */\n"
      "(function (root) { var M = " + json.dumps(marks, separators=(',', ':')) + ";\n"
      "  if (typeof module === 'object' && module.exports) module.exports = M; else root.RaBrandMarks = M;\n"
      "})(typeof self !== 'undefined' ? self : this);\n")
open(out, 'w').write(js)
print('brand-marks.js', len(js), 'bytes', file=sys.stderr)
