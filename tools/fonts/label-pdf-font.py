# FONT-RP-5: regenerate web/label-pdf-font.js. Needs fontTools (pip install fonttools), a dev tool,
# not a repo dependency. Usage: python3 tools/fonts/label-pdf-font.py "Manrope[wght].ttf" web/label-pdf-font.js
# Source: google/fonts ofl/manrope/Manrope[wght].ttf (sha256 3ae11c49...d6ae6).
import sys, json, base64, io
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset
src, out = sys.argv[1], sys.argv[2]
chars = list(range(0x20, 0x7F)) + [0x20B9, 0x2026, 0x00D7, 0x00B0, 0x2013, 0x2014, 0x00B7, 0x2019, 0x2018, 0x201C, 0x201D, 0x00B5, 0x00A0]
faces = {}
for name, w in [('regular', 400), ('bold', 700)]:
    f = instancer.instantiateVariableFont(TTFont(src), {'wght': w})
    opt = subset.Options(); opt.layout_features = []; opt.name_IDs = [0,1,2,3,4,5,6]; opt.hinting = False; opt.desubroutinize = True
    opt.notdef_outline = True; opt.glyph_names = False; opt.name_legacy = True; opt.drop_tables += ['GDEF','GPOS','GSUB','STAT','DSIG']
    sub = subset.Subsetter(opt); sub.populate(unicodes=chars); sub.subset(f)
    ps = 'Manrope-Regular' if w == 400 else 'Manrope-Bold'
    for rec in f['name'].names:
        if rec.nameID == 6: rec.string = ps
    # deterministic output: keep the upstream head timestamps rather than stamping 'now'
    f.recalcTimestamp = False
    buf = io.BytesIO(); f.save(buf); data = buf.getvalue()
    upm = f['head'].unitsPerEm; k = 1000 / upm
    cmap = f.getBestCmap(); order = f.getGlyphOrder(); hmtx = f['hmtx']
    faces[name] = {
        'ps': ps, 'bytes': len(data), 'ttf': base64.b64encode(data).decode(),
        'ascent': round(f['hhea'].ascent * k), 'descent': round(f['hhea'].descent * k),
        'cap': round(f['OS/2'].sCapHeight * k),
        'bbox': [round(v * k) for v in (f['head'].xMin, f['head'].yMin, f['head'].xMax, f['head'].yMax)],
        'cmap': {str(cp): order.index(g) for cp, g in sorted(cmap.items())},
        'w': [round(hmtx[g][0] * k) for g in order],
    }
    print(name, len(data), 'bytes ttf', len(order), 'glyphs', file=sys.stderr)
js = ("/* FONT-RP-5: Manrope for label PDFs -- static 400 and 700 instances of the upstream variable font\n"
      " * (google/fonts Manrope[wght].ttf, OFL 1.1, fonts/OFL-manrope.txt), subset with fontTools to Basic\n"
      " * Latin, the rupee sign and the label's punctuation. GENERATED by tools/fonts/label-pdf-font.py; do not\n"
      " * hand-edit. Loaded only when a PDF label is rendered (RaLabel.loadPdfFont). Widths in 1/1000 em,\n"
      " * indexed by glyph id. */\n"
      "(function (root) { var F = " + json.dumps(faces, separators=(',', ':')) + ";\n"
      "  if (typeof module === 'object' && module.exports) module.exports = F; else root.RaLabelPdfFont = F;\n"
      "})(typeof self !== 'undefined' ? self : this);\n")
open(out, 'w').write(js)
print('js', len(js), file=sys.stderr)
